import sys
from PySide2.QtWidgets import QApplication, QTextEdit, QVBoxLayout, QWidget, QPushButton
from PySide2.QtCore import Qt


class FunctionManual(QWidget):
    """功能说明文档查看器"""
    
    def __init__(self):
        super().__init__()
        self.setWindowTitle("表单设计器 - 功能说明")
        self.resize(900, 700)
        self._build_ui()
    
    def _build_ui(self):
        """构建界面"""
        layout = QVBoxLayout(self)
        
        # 文本显示区域
        text_edit = QTextEdit()
        text_edit.setReadOnly(True)
        text_edit.setMarkdown(self._get_manual_content())
        layout.addWidget(text_edit)
        
        # 关闭按钮
        close_btn = QPushButton("关闭")
        close_btn.clicked.connect(self.close)
        layout.addWidget(close_btn)
    
    def _get_manual_content(self) -> str:
        """获取说明文档内容"""
